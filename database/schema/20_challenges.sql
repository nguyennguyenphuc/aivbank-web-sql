-- postgres): `ALTER DEFAULT PRIVILEGES` cua file 16 chi tu cap quyen cho bang
-- do chinh vai tro do tao. Idempotent.
--
-- CAI GI NAM O DAY: chi ket qua - ai da giai bai nao, luc nao, bao nhieu lan
-- nop. DE BAI va DAP AN thi KHONG: chung nam trong backend/challenges/*.json,
-- mot thu muc may chu khong bao gio phuc vu ra ngoai. Cau SQL hoc vien nop
-- cung khong luu, chi luu ma bam - giong app.practice_events.
--
-- Diem cua khu vuc nay la BANG DIEM RIENG (quyet dinh 2026-11-07): khong cong
-- vao app.user_rewards (sao / kim cuong cua console).
-- ---------------------------------------------------------------------

\set ON_ERROR_STOP on
\connect aivb_app

CREATE TABLE IF NOT EXISTS app.challenge_attempts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text NOT NULL,
    challenge_id  text NOT NULL,
    submitted_at  text NOT NULL,
    passed        boolean NOT NULL,
    sql_hash      text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS challenge_attempts_user_idx
    ON app.challenge_attempts (username, challenge_id);

CREATE TABLE IF NOT EXISTS app.challenge_solved (
    username      text NOT NULL,
    challenge_id  text NOT NULL,
    domain        text NOT NULL,
    points        integer NOT NULL,
    attempts      integer NOT NULL,
    solved_at     text NOT NULL,
    PRIMARY KEY (username, challenge_id)
);
CREATE INDEX IF NOT EXISTS challenge_solved_domain_idx
    ON app.challenge_solved (domain, username);

COMMENT ON TABLE app.challenge_solved IS
    'Mot dong = lan giai DUNG DAU TIEN. Diem chi cong mot lan; nop lai bai da giai van ghi vao challenge_attempts nhung khong doi bang nay.';

-- File 16 da dat ALTER DEFAULT PRIVILEGES, nhung cap lai tuong minh cho chac:
-- chay file nay bang vai tro khac voi file 16 thi mac dinh do khong ap dung.
GRANT SELECT, INSERT, UPDATE, DELETE ON app.challenge_attempts, app.challenge_solved TO aivb_app_rw;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app TO aivb_app_rw;

DO $$
BEGIN
    IF NOT has_table_privilege('aivb_app_rw', 'app.challenge_solved', 'INSERT') THEN
        RAISE EXCEPTION 'aivb_app_rw thieu INSERT tren app.challenge_solved';
    END IF;
    -- Hoc vien dang nhap vao aivb_app nhung KHONG duoc doc bang nao: doc duoc
    -- challenge_solved la biet ai da giai bai nao truoc khi bang xep hang cho
    -- phep, va (te hon) tu sua diem neu co quyen ghi.
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aivb_class_student') THEN
        IF has_table_privilege('aivb_class_student', 'app.challenge_solved', 'SELECT')
           OR has_table_privilege('aivb_class_student', 'app.challenge_solved', 'INSERT')
           OR has_table_privilege('aivb_class_student', 'app.challenge_attempts', 'SELECT') THEN
            RAISE EXCEPTION 'DUNG LAI: hoc vien cham duoc bang tien do luyen SQL';
        END IF;
    END IF;
    RAISE NOTICE 'OK: app.challenge_* da dung quyen';
END $$;
