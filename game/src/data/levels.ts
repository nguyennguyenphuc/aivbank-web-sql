function createCanonicalLevel(id: number): LevelConfig {
  const worldId = Math.ceil(id / 6);
  const world = EXTRA_WORLD_NAMES[worldId - 5];
  const peak = id % 10 === 0;
  const hard = id % 5 === 0;
  const recovery = id % 10 === 1;
  const difficulty: LevelConfig['difficulty'] = peak ? 'boss' : hard ? 'hard' : recovery ? 'recovery' : 'normal';
  const colors: LevelConfig['allowedColors'] = recovery
    ? ['red', 'yellow', 'green', 'blue']
    : ['red', 'orange', 'yellow', 'green', 'blue', ...(hard ? ['purple' as const] : [])];
  const metadata = CANONICAL_CAMPAIGN[id - 1];
  const ice = id % 3 === 0 ? symmetricCells(id, 1).map(cell => ({ ...cell, level: hard ? 2 : 1 })) : undefined;
  const chocolate = id % 4 === 0 ? symmetricCells(id + 1, 1) : undefined;
  const variants = id >= 28 && id <= 30 ? APP_LEVEL_VARIANTS[id as 28 | 29 | 30] : undefined;
  return {
    id,
    worldId,
    worldNameVi: world[0],
    worldNameEn: world[1],
    worldTheme: world[2],
    nameVi: peak ? `Thử Thách Trùm Chương ${worldId}` : `Bài Học Kẹo Số ${id}`,
    nameEn: peak ? `Chapter ${worldId} Boss Challenge` : `Candy Lesson ${id}`,
    rows: 8,
    cols: 8,
    moves: peak ? 24 : recovery ? 30 : hard ? 22 : 27,
    starScores: [id * 500, id * 850, id * 1200],
    allowedColors: colors,
    objectives: peak ? [{
      type: 'DEFEAT_BOSS', target: 80 + id * 2, current: 0,
      descriptionVi: `Gây ${80 + id * 2} sát thương`, descriptionEn: `Deal ${80 + id * 2} damage`,
    }] : [{
      type: id % 3 === 0 ? 'CLEAR_ICE' : id % 4 === 0 ? 'CLEAR_CHOCOLATE' : 'SCORE',
      target: id % 3 === 0 || id % 4 === 0 ? 8 : id * 400,
      current: 0,
      descriptionVi: id % 3 === 0 ? 'Phá 8 lớp băng' : id % 4 === 0 ? 'Dọn 8 khối chocolate' : `Đạt ${id * 400} điểm`,
      descriptionEn: id % 3 === 0 ? 'Clear 8 ice layers' : id % 4 === 0 ? 'Clear 8 chocolates' : `Reach ${id * 400} score`,
    }],
    initialIce: ice,
    initialChocolate: chocolate,
    boss: peak ? {
      nameVi: `Giám Khảo Kẹo ${worldId}`, nameEn: `Candy Examiner ${worldId}`, avatar: '👑',
      maxHp: 80 + id * 2, currentHp: 80 + id * 2,
    } : undefined,
    tipVi: id === 30 ? 'Thông điệp bước hướng dẫn 4 được điều khiển theo phiên bản ứng dụng.' : 'Quan sát mục tiêu và tạo chuỗi kẹo đặc biệt.',
    tipEn: id === 30 ? 'Tutorial step 4 copy is selected by app version.' : 'Watch the objective and chain special candies.',
    seed: metadata.seed,
    contentRevision: metadata.revision,
    appVariant: variants ? 'v2.1.1' : undefined,
    tutorialMessageKey: metadata.tutorialMessageKey,
    difficulty,
  };
}

function symmetricCells(seed: number, pairs: number): Array<{ row: number; col: number }> {
  const cells: Array<{ row: number; col: number }> = [];
  for (let index = 0; index < pairs * 4; index++) {
    const row = 2 + ((seed + index) % 4);
    const col = 1 + ((seed * 3 + index) % 3);
    cells.push({ row, col }, { row, col: 7 - col });
  }
  return cells.filter((cell, index, all) => all.findIndex(other => other.row === cell.row && other.col === cell.col) === index);
}
