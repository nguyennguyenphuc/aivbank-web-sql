/** Retryable errors get a "Chạy lại" button. */
const RETRYABLE = new Set(['E_SERVICE_BUSY', 'E_TIMEOUT', 'E_CLIENT_NETWORK', 'E_INTERNAL']);

export function errorHint(code) {
  return HINTS[code] || 'Nếu không rõ nguyên nhân, hãy báo giảng viên kèm câu truy vấn của bạn.';
}

export function isRetryable(code) {
  return RETRYABLE.has(code);
}

export function isClientCode(code) {
  return typeof code === 'string' && code.startsWith('E_CLIENT_');
}
